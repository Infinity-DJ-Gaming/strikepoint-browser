// Compatibility implementation of the Source CUniformRandomStream/table generator.
// Inputs above are current native CS2; generator/decay constants are legacy source,
// NOT a claim that the closed CS2 executable is bit-identical. See PROVENANCE.md.
const f=Math.fround;
const lerp=(t,a,b)=>f(a+f(f(b-a)*t));
export const SOURCE_RECOIL_DEFAULTS=Object.freeze({
  tableSize:64, variance:f(.55), suppressionShots:4, suppressionFactor:f(.75),
  recoilScale:2, decayAngleExponential:8, decayAngleLinear:18,
  decayVelocity:4.5, recoilIndexDecayCoefficient:2, recoilIndexDecayThreshold:1.1,
});
export class SourceUniformRandom {
  constructor(seed=0){this.seed=-(Math.abs(seed)|0);this.last=0;this.shuffle=new Int32Array(32);}
  integer(){
    let k;
    if(this.seed<=0||!this.last){
      this.seed=Math.max(1,-this.seed);
      for(let j=39;j>=0;j--){k=Math.trunc(this.seed/127773);this.seed=16807*(this.seed-k*127773)-2836*k;if(this.seed<0)this.seed+=2147483647;if(j<32)this.shuffle[j]=this.seed;}
      this.last=this.shuffle[0];
    }
    k=Math.trunc(this.seed/127773);this.seed=16807*(this.seed-k*127773)-2836*k;
    if(this.seed<0)this.seed+=2147483647;
    const j=Math.trunc(this.last/67108864);this.last=this.shuffle[j];this.shuffle[j]=this.seed;
    return this.last;
  }
  float(low=0,high=1){
    // Source AM is double, assigned to float before clamping and range mapping.
    let unit=f(this.integer()/2147483647);
    if(unit>1-1.2e-7)unit=f(1-1.2e-7);
    return f(f(unit*f(high-low))+low);
  }
}
const select=(value,mode,fallback=0)=>Array.isArray(value)?value[mode]??value[0]??fallback:value??fallback;
export function generateRecoilTable(profile,{mode=0,...options}={}){
  if(typeof profile==='string')profile=NATIVE_RECOIL_PROFILES[profile.startsWith('weapon_')?profile:`weapon_${profile}`];
  if(!profile)throw new Error('Unknown native recoil profile');
  const defaults={...SOURCE_RECOIL_DEFAULTS,...options};
  const seed=profile.seed??profile.recoilSeed??0;
  const isAuto=profile.automatic??profile.m_bIsFullAuto??false;
  const sourceAngle=f(select(profile.angle??profile.recoilAngle??profile.m_flRecoilAngle,mode));
  const angleVariance=f(select(profile.angleVariance??profile.recoilVariance??profile.m_flRecoilAngleVariance,mode));
  const sourceMagnitude=f(select(profile.magnitude??profile.recoilMagnitude??profile.m_flRecoilMagnitude,mode));
  const magnitudeVariance=f(select(profile.magnitudeVariance??profile.recoilMagnitudeVariance??profile.m_flRecoilMagnitudeVariance,mode));
  const rng=new SourceUniformRandom(seed),table=[];
  let angle=0,magnitude=0;
  for(let shot=0;shot<defaults.tableSize;shot++){
    const nextAngle=f(sourceAngle+rng.float(-angleVariance,angleVariance));
    const nextMagnitude=f(sourceMagnitude+rng.float(-magnitudeVariance,magnitudeVariance));
    angle=isAuto&&shot>0?lerp(f(defaults.variance),angle,nextAngle):nextAngle;
    magnitude=isAuto&&shot>0?lerp(f(defaults.variance),magnitude,nextMagnitude):nextMagnitude;
    if(isAuto&&shot<defaults.suppressionShots){
      // Source intentionally feeds this suppressed magnitude into the next Lerp.
      const suppression=lerp(f(shot/defaults.suppressionShots),f(defaults.suppressionFactor),1);
      magnitude=f(magnitude*suppression);
    }
    const radians=angle*Math.PI/180;
    table.push(Object.freeze({angle,magnitude,x:f(Math.sin(radians)*magnitude),y:f(Math.cos(radians)*magnitude)}));
  }
  return table;
}
export function recoveryTime(profile,recoilIndex=0,{crouching=false,airborne=false}={}){
  const base=profile[crouching||airborne?'recoveryCrouch':'recoveryStand'];
  if(airborne)return base*4;
  const final=profile[crouching?'recoveryCrouchFinal':'recoveryStandFinal'];
  if(final<0||final===undefined)return base;
  const start=profile.recoveryStartBullet,end=profile.recoveryEndBullet,index=Math.trunc(recoilIndex);
  const t=end===start?(index>=end?1:0):Math.min(1,Math.max(0,(index-start)/(end-start)));
  return base+(final-base)*t;
}
export function decayRecoilIndex(index,dt,timeSinceShot,cycleTime){
  return timeSinceShot>cycleTime*SOURCE_RECOIL_DEFAULTS.recoilIndexDecayThreshold?
    index*Math.exp(-Math.LN10*SOURCE_RECOIL_DEFAULTS.recoilIndexDecayCoefficient*dt):index;
}
// Legacy CCSGameMovement::DecayAimPunchAngle in degrees/degree velocity per second.
// Uses one fixed simulation tick. Call at fixed dt (1/64), interpolate only render.
export function decayAimPunch(punch,velocity,dt){
  const exponential=Math.exp(-SOURCE_RECOIL_DEFAULTS.decayAngleExponential*dt);
  let x=punch.x*exponential,y=punch.y*exponential;
  const length=Math.hypot(x,y),linear=SOURCE_RECOIL_DEFAULTS.decayAngleLinear*dt;
  const factor=length>linear?1-linear/length:0;x*=factor;y*=factor;
  x+=velocity.x*dt*.5;y+=velocity.y*dt*.5;
  const velocityDecay=Math.exp(-SOURCE_RECOIL_DEFAULTS.decayVelocity*dt);
  velocity.x*=velocityDecay;velocity.y*=velocityDecay;
  x+=velocity.x*dt*.5;y+=velocity.y*dt*.5;
  punch.x=x;punch.y=y;
  return punch;
}
